    @MainActor
    private func buildStoryOutline() async {
        isBuildingOutline = true
        storyOutlineError = nil
        outlineExpansionProgress = "Drafting quick outline..."
        defer { isBuildingOutline = false }

        do {
            let quickOutline = try await ai.createStoryOutline(wizard: wizard)
            storyOutline = quickOutline

            if let firstBeat = wizard.beats.first(where: { quickOutline[$0.key] != nil }) {
                selectedBeatKey = firstBeat.key
            }

            let outlineBeats = wizard.beats.compactMap { quickOutline[$0.key] != nil ? $0 : nil }
            for (index, beat) in outlineBeats.enumerated() {
                guard let quickLine = quickOutline[beat.key] else { continue }
                if Task.isCancelled { throw CancellationError() }

                outlineExpansionProgress = "Expanding beat \(index + 1) of \(outlineBeats.count): \(beat.title)"

                if let expanded = await ai.expandBeatOutline(quickLine, beat: beat, wizard: wizard) {
                    let cleaned = expanded.trimmingCharacters(in: .whitespacesAndNewlines)
                    guard !cleaned.isEmpty else { continue }
                    storyOutline[beat.key] = cleaned
                    wizard.entries[beat.key] = cleaned
                }
            }

            if let firstBeat = wizard.beats.first(where: { storyOutline[$0.key] != nil }) {
                selectedBeatKey = firstBeat.key
            }
            outlineExpansionProgress = "Finished expanding \(storyOutline.count) beats."
        } catch is CancellationError {
            outlineExpansionProgress = nil
            return
        }
        catch {
            storyOutlineError = error.localizedDescription
            outlineExpansionProgress = nil
        }
    }

    @MainActor
    private func askAssistant() async {
        let prompt = assistantPrompt.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !prompt.isEmpty else { return }
        guard let beat = selectedBeat else { return }
        isPrompting = true
        defer { isPrompting = false }

        if let result = await ai.answerPrompt(prompt, beat: beat, wizard: wizard) {
            assistantSuggestion = result
            assistantSuggestionBeatKey = beat.key
        }
    }

    private var selectedBeat: BeatTemplate? {
        wizard.beats.first(where: { $0.key == selectedBeatKey }) ?? wizard.beats.first
    }

