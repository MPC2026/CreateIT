private struct BeatDraftTextEditor: NSViewRepresentable {
    @Binding var text: String
    var onFocus: () -> Void

    func makeCoordinator() -> Coordinator {
        Coordinator(text: $text, onFocus: onFocus)
    }

    func makeNSView(context: Context) -> NSScrollView {
        let scrollView = BeatEditorScrollView()
        scrollView.onActivate = onFocus
        scrollView.drawsBackground = false
        scrollView.hasVerticalScroller = true
        scrollView.hasHorizontalScroller = false
        scrollView.autohidesScrollers = true
        scrollView.borderType = .noBorder
        scrollView.backgroundColor = .clear
        scrollView.focusRingType = .none

        let textView = BeatEditorTextView()
        textView.onActivate = onFocus
        textView.delegate = context.coordinator
        textView.isRichText = false
        textView.importsGraphics = false
        textView.isEditable = true
        textView.isSelectable = true
        textView.allowsUndo = true
        textView.isVerticallyResizable = true
        textView.isHorizontallyResizable = false
        textView.autoresizingMask = [.width]
        textView.textContainerInset = NSSize(width: 8, height: 8)
        textView.textContainer?.widthTracksTextView = true
        textView.textContainer?.containerSize = NSSize(width: 0, height: CGFloat.greatestFiniteMagnitude)
        textView.drawsBackground = true
        textView.backgroundColor = .textBackgroundColor
        textView.font = NSFont.preferredFont(forTextStyle: .body)
        textView.string = text

        scrollView.documentView = textView
        context.coordinator.textView = textView
        return scrollView
    }

    func updateNSView(_ nsView: NSScrollView, context: Context) {
        guard let textView = context.coordinator.textView else { return }
        if textView.string != text {
            textView.string = text
        }
        textView.backgroundColor = .textBackgroundColor
    }

    final class Coordinator: NSObject, NSTextViewDelegate {
        @Binding var text: String
        var onFocus: () -> Void
        weak var textView: BeatEditorTextView?

        init(text: Binding<String>, onFocus: @escaping () -> Void) {
            _text = text
            self.onFocus = onFocus
        }

        func textDidBeginEditing(_ notification: Notification) {
            onFocus()
        }

        func textDidChange(_ notification: Notification) {
            guard let textView else { return }
            text = textView.string
            onFocus()
        }
    }
}

private final class BeatEditorScrollView: NSScrollView {
    var onActivate: (() -> Void)?

    override func mouseDown(with event: NSEvent) {
        onActivate?()
        super.mouseDown(with: event)
    }
}

private final class BeatEditorTextView: NSTextView {
    var onActivate: (() -> Void)?

    override func becomeFirstResponder() -> Bool {
        let result = super.becomeFirstResponder()
        if result { onActivate?() }
        return result
    }

    override func mouseDown(with event: NSEvent) {
        onActivate?()
        super.mouseDown(with: event)
    }
}

private struct BeatAIDraftSheetView: View {
    @Environment(\.dismiss) private var dismiss
    @EnvironmentObject private var wizard: WizardState
    @EnvironmentObject private var ai: AIAssistant

    let beat: BeatTemplate
    let draftAction: () async -> Bool

    @State private var isDrafting = false
    @State private var errorMessage: String?

    private var label: String {
        (wizard.entries[beat.key]?.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty ?? true)
            ? "Draft with AI"
            : "Rewrite with AI"
    }

    var body: some View {
        VStack(alignment: .leading, spacing: 18) {
            VStack(alignment: .leading, spacing: 6) {
                Text(label)
                    .font(.title2.weight(.bold))
                Text(beat.title)
                    .font(.headline)
                    .foregroundStyle(.secondary)
                Text(beat.purpose)
                    .font(.callout)
                    .foregroundStyle(.secondary)
                    .fixedSize(horizontal: false, vertical: true)
            }

            // Sample movie reference section removed in v3.0b24

            if let existing = wizard.entries[beat.key], !existing.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
                VStack(alignment: .leading, spacing: 6) {
                    Text("Current draft")
                        .font(.caption.weight(.semibold))
                        .foregroundStyle(.secondary)
                    Text(existing)
                        .font(.callout)
                        .fixedSize(horizontal: false, vertical: true)
                }
                .padding(12)
                .frame(maxWidth: .infinity, alignment: .leading)
                .background(
                    RoundedRectangle(cornerRadius: 10, style: .continuous)
                        .fill(Color(nsColor: .controlBackgroundColor)))
            }

            if let errorMessage {
                Text(errorMessage)
                    .font(.caption)
                    .foregroundStyle(.orange)
            }

            HStack {
                Button {
                    dismiss()
                } label: {
                    Text("Cancel")
                }
                .buttonStyle(.bordered)

                Spacer()

                Button {
                    Task { await startDraft() }
                } label: {
                    if isDrafting {
                        HStack(spacing: 6) {
                            ProgressView().controlSize(.small)
                            Text("Drafting…")
                        }
                    } else {
                        Label(label, systemImage: "sparkles")
                    }
                }
                .buttonStyle(.borderedProminent)
                .disabled(isDrafting || !ai.isConfigured)
            }
        }
        .padding(24)
        .frame(maxWidth: .infinity, maxHeight: .infinity, alignment: .leading)
    }

    @MainActor
    private func startDraft() async {
        isDrafting = true
        errorMessage = nil
        defer { isDrafting = false }
        if await draftAction() {
            dismiss()
        } else if !Task.isCancelled {
            errorMessage = "The AI draft could not be created. Try again after checking LM Studio."
        }
    }
}

