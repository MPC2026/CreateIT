    private func exportBeatsToFinalDraft(openAfterWrite: Bool) {
        let panel = NSSavePanel()
        if let fdxType = UTType(filenameExtension: "fdx") {
            panel.allowedContentTypes = [fdxType]
        }

        let safeTitle = wizard.projectTitle.isEmpty ? "CreateIT Beats" : "\(wizard.projectTitle) Beats"
        panel.nameFieldStringValue = "\(safeTitle).fdx"
        panel.canCreateDirectories = true
        panel.allowsOtherFileTypes = false
        panel.treatsFilePackagesAsDirectories = false
        panel.isExtensionHidden = false

        guard panel.runModal() == .OK, let url = panel.url else { return }

        let fdx = FDXExporter.export(
            from: wizard,
            beatElement: beatElement,
            includeGuidance: includeGuidance,
            includeSceneScript: false)

        do {
            try fdx.write(to: url, atomically: true, encoding: .utf8)
            if openAfterWrite {
                NSWorkspace.shared.open(url)
            exportStatusMessage = "Opened \(url.lastPathComponent) in Final Draft."
        } else {
                exportStatusMessage = "Saved \(url.lastPathComponent)."
            }
            exportStatusIsError = false
        } catch {
            exportStatusMessage = error.localizedDescription
            exportStatusIsError = true
        }
    }

