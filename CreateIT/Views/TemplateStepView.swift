    }

    private func applyOutlineToAllBeats() {
        for beat in wizard.beats {
            if let text = storyOutline[beat.key] {
                wizard.entries[beat.key] = text
            }
        }
        if let firstBeat = wizard.beats.first(where: { storyOutline[$0.key] != nil }) {
            selectedBeatKey = firstBeat.key
        }
        clearSuggestion()
    }

    private func clearStoryOutline() {
        storyOutline = [:]
        storyOutlineError = nil
        outlineExpansionProgress = nil
    }

    private func startAIAction(_ operation: @escaping @Sendable () async -> Void) {
        cancelAIAction()
        let actionID = UUID()
        activeAIActionID = actionID
        activeAITask = Task {
            await operation()
            await MainActor.run {
                if activeAIActionID == actionID {
                    activeAIActionID = nil
                    activeAITask = nil
                }
            }
        }
    }

    private func cancelAIAction() {
        activeAITask?.cancel()
        activeAITask = nil
        activeAIActionID = nil
        isPrompting = false
        isBuildingOutline = false
        outlineExpansionProgress = nil
    }

    private var outlineButtonLabel: String {
        outlineExpansionProgress ?? "Creating..."
    }

    @MainActor
    private func draftBeatWithAI(_ beat: BeatTemplate) async -> Bool {
        guard let result = await ai.draftBeat(beat, wizard: wizard) else { return false }
        wizard.entries[beat.key] = result
        selectedBeatKey = beat.key
        return true
    }
}

