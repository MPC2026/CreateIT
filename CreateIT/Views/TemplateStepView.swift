    private func syncSelectedBeat() {
        guard let first = wizard.beats.first else {
            selectedBeatKey = ""
            return
        }
        if wizard.beats.contains(where: { $0.key == selectedBeatKey }) {
            syncAssistantPrompt()
            return
        }
        selectedBeatKey = first.key
    }

    private func syncAssistantPrompt() {
        guard let beat = selectedBeat else {
            assistantPrompt = ""
            assistantPromptSourceBeatKey = nil
            assistantPromptIsAutoGenerated = true
            clearSuggestion()
            return
        }

        let generated = autoPrompt(for: beat)
        if assistantPrompt.isEmpty || assistantPromptIsAutoGenerated || assistantPromptSourceBeatKey != beat.key {
            assistantPrompt = generated
            assistantPromptSourceBeatKey = beat.key
            assistantPromptIsAutoGenerated = true
            clearSuggestion()
        }
    }

    private func autoPrompt(for beat: BeatTemplate) -> String {
        let draft = currentDraftText(for: beat)
        let draftAction = draft.isEmpty
            ? "Draft this beat from scratch."
            : "Rewrite this beat to make it sharper and more dramatic."
        let timing = wizard.runtime.map { beat.timing(for: $0) } ?? "Unknown"

        return """
        Beat Brief
        Title: \(beat.title)
        Act: \(beat.actLabel)
        Timing: \(timing)

        Purpose:
        \(beat.purpose)

        Current Draft:
        \(draft.isEmpty ? "No draft yet." : draft)

        Request:
        \(draftAction)
        """
    }

    private func currentDraftText(for beat: BeatTemplate) -> String {
        wizard.entries[beat.key]?
            .trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
    }

    private func useSuggestion() {
        guard let beat = selectedBeat, let assistantSuggestion else { return }
        let current = currentDraftText(for: beat)
        let merged = mergeDraft(current: current, suggestion: assistantSuggestion)
        wizard.entries[beat.key] = merged
        clearSuggestion()
        syncAssistantPrompt()
    }

    private func mergeDraft(current: String, suggestion: String) -> String {
        let currentSentences = sentenceList(from: current)
        let suggestionSentences = sentenceList(from: suggestion)

        guard !currentSentences.isEmpty else { return suggestion.trimmingCharacters(in: .whitespacesAndNewlines) }
        guard !suggestionSentences.isEmpty else { return current.trimmingCharacters(in: .whitespacesAndNewlines) }

        let count = max(currentSentences.count, suggestionSentences.count)
        var merged: [String] = []
        for index in 0..<count {
            let original = index < currentSentences.count ? currentSentences[index] : nil
            let rewritten = index < suggestionSentences.count ? suggestionSentences[index] : nil

            switch (original, rewritten) {
            case let (_, rewritten?):
                merged.append(rewritten)
            case let (original?, nil):
                merged.append(original)
            case (nil, nil):
                break
            }
        }
        return merged.joined(separator: " ")
    }

    private func sentenceList(from text: String) -> [String] {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return [] }

        let nsText = trimmed as NSString
        var sentences: [String] = []
        nsText.enumerateSubstrings(
            in: NSRange(location: 0, length: nsText.length),
            options: [.bySentences, .substringNotRequired]
        ) { _, range, _, _ in
            let sentence = nsText.substring(with: range).trimmingCharacters(in: .whitespacesAndNewlines)
            if !sentence.isEmpty {
                sentences.append(sentence)
            }
        }
        return sentences.isEmpty ? [trimmed] : sentences
    }

    private func clearSuggestion() {
        assistantSuggestion = nil
        assistantSuggestionBeatKey = nil
    }

